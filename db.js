async function seed(c) {
  for (let i = 0; i < SECTIONS.length; i++) {
    const [name, cats] = SECTIONS[i];
    const [{ id: sid }] = await c.query('INSERT INTO forum.sections(name, sort) VALUES($1, $2) RETURNING id', [name, i]);
    for (let j = 0; j < cats.length; j++) {
      const [slug, icon, cname, desc] = cats[j];
      await c.query('INSERT INTO forum.categories(section_id, slug, icon, name, description, sort) VALUES($1,$2,$3,$4,$5,$6)', [sid, slug, icon, cname, desc, j]);
    }
  }
  const now = Date.now();
  const [{ id: sys }] = await c.query(
    "INSERT INTO forum.users(username, pass, role, bio, created_at) VALUES('ytconsole', NULL, 'admin', 'Forumun resmi hesabı.', $1) RETURNING id", [now]);
  const [{ id: cat }] = await c.query("SELECT id FROM forum.categories WHERE slug = 'duyurular'");
  const [{ id: tid }] = await c.query(
    'INSERT INTO forum.threads(category_id, user_id, title, created_at, last_post_at, last_post_user, pinned, locked) VALUES($1,$2,$3,$4,$4,$2,1,1) RETURNING id',
    [cat, sys, "ytconsole'a hoş geldiniz! (Kurallar)", now]);
  await c.query('INSERT INTO forum.posts(thread_id, user_id, body, created_at) VALUES($1,$2,$3,$4)', [tid, sys, WELCOME, now]);
}

// Tabloları oluştur ve ilk verileri ekle (sunucu başına bir kez çalışır)
let ready = null;
function init() {
  if (!ready) {
    ready = tx(async (c) => {
      await c.query('SELECT pg_advisory_xact_lock(712001)');
      await c.exec(SCHEMA);
      const [{ n }] = await c.query('SELECT COUNT(*)::int AS n FROM forum.sections');
      if (n === 0) await seed(c);
    }).catch((e) => { ready = null; throw e; });
  }
  return ready;
}

async function getMeta(k) {
  const r = await one('SELECT v FROM forum.meta WHERE k = $1', [k]);
  return r ? r.v : null;
}
const setMeta = (k, v) => query('INSERT INTO forum.meta(k, v) VALUES($1, $2) ON CONFLICT (k) DO UPDATE SET v = EXCLUDED.v', [k, v]);

module.exports = { query, one, tx, init, getMeta, setMeta };
