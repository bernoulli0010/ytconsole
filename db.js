// Veritabanı katmanı: Postgres.
//  - DATABASE_URL tanımlıysa (Vercel + Supabase) gerçek Postgres'e bağlanır.
//  - Tanımlı değilse yerel geliştirme için gömülü Postgres (PGlite) kullanır: data/pg klasörü.
// Tüm tablolar "forum" şemasında durur; Supabase'in herkese açık API'si (public şeması) bunlara erişemez.
const path = require('path');

const INT8 = 20;
let impl = null;

function createImpl() {
  if (process.env.DATABASE_URL) {
    const { Pool, types } = require('pg');
    types.setTypeParser(INT8, (v) => Number(v));
    const u = new URL(process.env.DATABASE_URL);
    u.searchParams.delete('sslmode');
    const local = /^(localhost|127\.0\.0\.1|\[::1\])$/.test(u.hostname);
    const pool = new Pool({
      connectionString: u.toString(),
      ssl: local ? false : { rejectUnauthorized: false },
      max: Number(process.env.PG_POOL_MAX) || 3,
      idleTimeoutMillis: 10000,
      connectionTimeoutMillis: 10000,
    });
    const wrap = (c) => ({
      query: (sql, p) => c.query(sql, p).then((r) => r.rows),
      exec: (sql) => c.query(sql).then(() => undefined),
    });
    return {
      ...wrap(pool),
      async tx(fn) {
        const c = await pool.connect();
        try {
          await c.query('BEGIN');
          const r = await fn(wrap(c));
          await c.query('COMMIT');
          return r;
        } catch (e) {
          try { await c.query('ROLLBACK'); } catch { /* yoksay */ }
          throw e;
        } finally {
          c.release();
        }
      },
    };
  }

  if (process.env.VERCEL) throw new Error('DATABASE_URL ortam değişkeni tanımlı değil. Vercel > Settings > Environment Variables bölümüne Supabase bağlantı adresini ekle.');

  // Değişken adla require: Vercel paketleyicisi bu geliştirme bağımlılığını fonksiyona eklemesin.
  const mod = '@electric-sql/pglite';
  const { PGlite } = require(mod);
  const parsers = { [INT8]: (v) => Number(v) };
  const db = new PGlite(process.env.DATA_DIR || path.join(__dirname, 'data', 'pg'));
  const wrap = (c) => ({
    query: (sql, p) => c.query(sql, p, { parsers }).then((r) => r.rows),
    exec: (sql) => c.exec(sql).then(() => undefined),
  });
  return { ...wrap(db), tx: (fn) => db.transaction((t) => fn(wrap(t))) };
}

function get() {
  if (!impl) impl = createImpl();
  return impl;
}

const query = (sql, params = []) => get().query(sql, params);
const one = async (sql, params = []) => (await get().query(sql, params))[0];
const tx = (fn) => get().tx(fn);

